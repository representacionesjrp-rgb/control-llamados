import java.security.cert.X509Certificate
import javax.net.ssl.HttpsURLConnection
import javax.net.ssl.SSLContext
import javax.net.ssl.SSLSocketFactory
import javax.net.ssl.TrustManagerFactory
import javax.net.ssl.X509TrustManager

/**
 * The server certificate (workers.dev, Let's Encrypt) chains to ISRG Root X1/X2, which Android
 * only trusts since 7.1.1. On older phones (e.g. ZTE Blade A602 with Android 6) we trust those
 * two roots in addition to the phone's own ones. Newer phones are left untouched.
 */
object OldAndroidTls {
    private val factory: SSLSocketFactory? by lazy { runCatching { build() }.getOrNull() }

    fun apply(connection: HttpsURLConnection) {
        if (Build.VERSION.SDK_INT >= 25) return
        factory?.let { connection.sslSocketFactory = it }
    }

    private fun build(): SSLSocketFactory {
        val keyStore = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
        val system = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm())
            .apply { init(null as KeyStore?) }
            .trustManagers.filterIsInstance<X509TrustManager>().first()
        system.acceptedIssuers.forEachIndexed { i, cert -> keyStore.setCertificateEntry("system-$i", cert) }
        val certificates = CertificateFactory.getInstance("X.509")
        listOf(ISRG_ROOT_X1, ISRG_ROOT_X2).forEachIndexed { i, pem ->
            val cert = certificates.generateCertificate(pem.trim().byteInputStream()) as X509Certificate
            keyStore.setCertificateEntry("isrg-$i", cert)
        }
        val trust = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply { init(keyStore) }
        return SSLContext.getInstance("TLS").apply { init(null, trust.trustManagers, null) }.socketFactory
    }

